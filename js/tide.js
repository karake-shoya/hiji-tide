// 天文引数。1899-12-31 12:00 UTC を基準にした多項式で求める
function astro(utMs) {
  const ref = Date.UTC(1899, 11, 31, 12, 0, 0);
  const d = (utMs - ref) / 86400000,
    T = d / 36525;
  const m = (x) => ((x % 360) + 360) % 360;
  return {
    s: m(277.0247 + 481267.8906 * T + 0.002 * T * T),
    h: m(280.1895 + 36000.7689 * T + 0.0003 * T * T),
    p: m(334.3853 + 4069.034 * T - 0.0103 * T * T),
    N: m(259.156 - 1934.142 * T + 0.0021 * T * T),
    p1: m(281.2208 + 1.7192 * T + 0.00045 * T * T),
  };
}

// 月の昇交点による18.6年周期の補正。[振幅倍率 f, 位相補正 u]
function nodal(kind, N) {
  const n = N * D2R,
    c = Math.cos,
    s = Math.sin;
  switch (kind) {
    case "M2": {
      const f = 1.0004 - 0.0373 * c(n) + 0.0002 * c(2 * n);
      return [f, -2.14 * s(n)];
    }
    case "O1":
      return [1.0089 + 0.1871 * c(n) - 0.0147 * c(2 * n) + 0.0014 * c(3 * n), 10.8 * s(n) - 1.34 * s(2 * n) + 0.19 * s(3 * n)];
    case "K1":
      return [1.006 + 0.115 * c(n) - 0.0088 * c(2 * n) + 0.0006 * c(3 * n), -8.86 * s(n) + 0.68 * s(2 * n) - 0.07 * s(3 * n)];
    case "K2":
      return [1.0241 + 0.2863 * c(n) + 0.0083 * c(2 * n) - 0.0015 * c(3 * n), -17.74 * s(n) + 0.68 * s(2 * n) - 0.04 * s(3 * n)];
    case "J1":
      return [1.0129 + 0.1676 * c(n) - 0.017 * c(2 * n) + 0.0016 * c(3 * n), -12.94 * s(n) + 1.34 * s(2 * n) - 0.19 * s(3 * n)];
    case "OO1":
      return [1.1027 + 0.6504 * c(n) + 0.0317 * c(2 * n) - 0.0014 * c(3 * n), -36.68 * s(n) + 4.02 * s(2 * n) - 0.57 * s(3 * n)];
    case "Mm":
      return [1.0 - 0.13 * c(n) + 0.0013 * c(2 * n), 0];
    case "Mf":
      return [1.0429 + 0.4135 * c(n) - 0.004 * c(2 * n), -23.74 * s(n) + 2.68 * s(2 * n) - 0.38 * s(3 * n)];
    case "M4": {
      const f = 1.0004 - 0.0373 * c(n) + 0.0002 * c(2 * n);
      return [f * f, 2 * (-2.14 * s(n))];
    }
    case "M6": {
      const f = 1.0004 - 0.0373 * c(n) + 0.0002 * c(2 * n);
      return [f * f * f, 3 * (-2.14 * s(n))];
    }
    default:
      return [1, 0];
  }
}

/**
 * 指定時刻の推算潮位（cm）。
 * @param {number} realMs 実時刻のミリ秒（Date.now() と同じ基準）
 */
export function tide(realMs) {
  const a = astro(realMs);
  const jst = new Date(realMs + 9 * 3600000);
  const t = jst.getUTCHours() + jst.getUTCMinutes() / 60 + jst.getUTCSeconds() / 3600;
  const tau = 15 * t + a.h - a.s;
  let sum = Z0;
  for (const [, A, kap, d, ph, kind] of CONST) {
    const V = d[0] * tau + d[1] * a.s + d[2] * a.h + d[3] * a.p + d[4] * a.N + d[5] * a.p1 + ph;
    const [f, u] = nodal(kind, a.N);
    sum += f * A * Math.cos((V + u - kap) * D2R);
  }
  return sum;
}
