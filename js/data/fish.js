/** その月に名前が挙がる魚。旬の月を先に並べ、初心者向けを優先する */
export function fishOfMonth(month) {
  return FISH.filter((f) => f.months.includes(month)).sort((a, b) => {
    const ap = a.peak.includes(month) ? 0 : 1;
    const bp = b.peak.includes(month) ? 0 : 1;
    if (ap !== bp) return ap - bp;
    if (a.easy !== b.easy) return a.easy ? -1 : 1;
    return 0;
  });
}
